@app.route('/login', methods=['GET','POST'])
def login():
    if current_user(): return redirect(url_for('dashboard'))
    if request.method=='POST':
        username=request.form.get('username','').strip()
        password=request.form.get('password','')
        user=rows('SELECT * FROM users WHERE username=?',(username,))
        valid=False
        if user and user[0]['active']:
            stored=user[0]['password_hash']
            valid=check_password_hash(stored,password) if stored.startswith(('scrypt:','pbkdf2:')) else stored==hashlib.sha256(password.encode()).hexdigest()
        if valid:
            session['user']={'username':user[0]['username'],'role':user[0]['role'],'name':user[0]['full_name']}
            return redirect(url_for('dashboard'))
        flash('Incorrect username or password.','error')
    return render_template('login.html')

