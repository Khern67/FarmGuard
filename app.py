@app.post('/users/<int:user_id>/toggle')
@owner_required
def toggle_user(user_id):
    if user_id == rows('SELECT id FROM users WHERE username=?',(current_user()['username'],))[0]['id']:
        flash('You cannot deactivate your own account.','error')
    else:
        target=rows('SELECT role,active FROM users WHERE id=?',(user_id,))
        if target and target[0]['active'] and target[0]['role']=='Owner' and rows("SELECT COUNT(*) AS n FROM users WHERE role='Owner' AND active=1")[0]['n']<=1:
            flash('At least one active Owner account must remain.','error')
        else:
            with get_conn() as conn: conn.execute('UPDATE users SET active=CASE active WHEN 1 THEN 0 ELSE 1 END WHERE id=?',(user_id,))
            flash('User account status updated.','success')
    return redirect(url_for('users_page'))

