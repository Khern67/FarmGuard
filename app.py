def rows(query, params=()):
    with get_conn() as conn: return conn.execute(query, params).fetchall()

def get_crops():
    # Hash Table is used as an in-memory index for fast crop ID/name lookup during request processing.
    data=rows('''SELECT c.*, f.name AS farm_name FROM crops c LEFT JOIN farms f ON c.farm_id=f.id ORDER BY c.id DESC''')
    index=HashTable()
    for crop in data: index.insert(str(crop['id']), dict(crop))
    return data, index

def get_reports():
    # Linked List preserves the ordered observation stream; Merge Sort is used for display ordering.
    data=rows('''SELECT r.*, c.crop_name, c.section, f.name AS farm_name FROM reports r LEFT JOIN crops c ON r.crop_id=c.id LEFT JOIN farms f ON r.farm_id=f.id''')
    history=LinkedList()
    for item in sorted(data, key=lambda x: x['id']): history.append(dict(item))
    return merge_sort(history.to_list(), key=lambda x: x.get('report_date') or '' )[::-1]

def build_farm_tree(farms, crops):
    forest=[]
    for farm in farms:
        tree=FarmTree(farm['name'])
        for crop in crops:
            if crop['farm_id']==farm['id']: tree.add_path(crop['crop_name'], crop['section'] or 'Unassigned section')
        forest.append((farm['name'], tree.preorder()))
    return forest

