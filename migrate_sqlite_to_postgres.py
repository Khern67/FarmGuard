
import os
import sqlite3
import psycopg
from dotenv import load_dotenv

load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL is missing. Check your .env file.")

TABLES = {
    "users": [
        "id", "username", "password_hash", "role", "full_name", "active"
    ],
    "farms": [
        "id", "name", "owner", "location", "latitude", "longitude",
        "created_at"
    ],
    "crops": [
        "id", "farm_id", "crop_name", "crop_type", "section",
        "area_acres", "planting_date", "growth_stage", "latitude",
        "longitude", "created_at"
    ],
    "reports": [
        "id", "crop_id", "farm_id", "reporter", "report_date",
        "symptoms", "affected_area", "progression", "plant_condition",
        "recurrence_count", "severity", "urgency_score", "priority",
        "notes", "status", "inspected_by", "inspected_at", "created_at"
    ]
}

CREATE_TABLES = """
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL,
    full_name TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS farms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    owner TEXT,
    location TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS crops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id BIGINT REFERENCES farms(id),
    crop_name TEXT NOT NULL,
    crop_type TEXT NOT NULL,
    section TEXT,
    area_acres DOUBLE PRECISION DEFAULT 0,
    planting_date TEXT,
    growth_stage TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_id BIGINT REFERENCES crops(id),
    farm_id BIGINT REFERENCES farms(id),
    reporter TEXT,
    report_date TEXT,
    symptoms TEXT,
    affected_area DOUBLE PRECISION,
    progression TEXT,
    plant_condition TEXT,
    recurrence_count INTEGER,
    severity TEXT,
    urgency_score DOUBLE PRECISION,
    priority TEXT,
    notes TEXT,
    status TEXT DEFAULT 'Pending',
    inspected_by TEXT,
    inspected_at TEXT,
    created_at TEXT NOT NULL
);
"""


def migrate():
    source = sqlite3.connect("farmguard.db")
    source.row_factory = sqlite3.Row

    try:
        with psycopg.connect(
            DATABASE_URL,
            sslmode="require"
        ) as target:

            with target.cursor() as cursor:
                cursor.execute(CREATE_TABLES)

                # Stop if Neon already contains records.
                for table in TABLES:
                    cursor.execute(
                        f"SELECT COUNT(*) FROM {table}"
                    )
                    count = cursor.fetchone()[0]

                    if count > 0:
                        raise RuntimeError(
                            f"Neon table '{table}' already contains "
                            f"{count} records. Migration stopped safely."
                        )

                # Import parent tables before dependent tables.
                for table, columns in TABLES.items():
                    records = source.execute(
                        f"SELECT * FROM {table}"
                    ).fetchall()

                    if not records:
                        print(f"{table}: no records to import.")
                        continue

                    column_names = ", ".join(columns)
                    placeholders = ", ".join(
                        ["%s"] * len(columns)
                    )

                    query = (
                        f"INSERT INTO {table} ({column_names}) "
                        f"VALUES ({placeholders})"
                    )

                    values = [
                        tuple(record[column] for column in columns)
                        for record in records
                    ]

                    cursor.executemany(query, values)

                    print(
                        f"{table}: {len(records)} records imported."
                    )

                # Synchronize identity sequences with imported IDs.
                for table in TABLES:
                    cursor.execute(
                        f"""
                        SELECT setval(
                            pg_get_serial_sequence(
                                'public.{table}', 'id'
                            ),
                            COALESCE((SELECT MAX(id) FROM {table}), 1),
                            EXISTS(SELECT 1 FROM {table})
                        )
                        """
                    )

            print("\nMigration completed successfully!")

    finally:
        source.close()


if __name__ == "__main__":
    migrate()
